// Builds the static site into dist/ (production) or dist-test/ (--test).
// ER-D6: only test builds set TEST_STANDALONE = true; production never does.
import { cpSync, mkdirSync, rmSync, writeFileSync, readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const test = process.argv.includes('--test');
const out = test ? 'dist-test' : 'dist';
const files = ['index.html', 'styles.css', 'app.js', 'engine.js', 'log.js', 'labels.js', 'nav.js', 'store.js'];
const dirs = ['fonts', 'fixtures'];

rmSync(out, { recursive: true, force: true });
mkdirSync(`${out}/vendor`, { recursive: true });
for (const f of files) cpSync(f, `${out}/${f}`);
for (const d of dirs) cpSync(d, `${out}/${d}`, { recursive: true });
cpSync('node_modules/big.js/big.mjs', `${out}/vendor/big.mjs`);

let build = 'dev';
try { build = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch {}
writeFileSync(`${out}/config.js`,
  `// Generated by scripts/build.mjs\nexport const TEST_STANDALONE = ${test};\nexport const BUILD = '${build}${test ? '-test' : ''}';\n`);

if (!test) {
  const bundle = files.concat('config.js').map(f => readFileSync(`${out}/${f}`, 'utf8')).join('\n');
  if (/TEST_STANDALONE\s*=\s*true/.test(bundle)) { console.error('production build contains TEST_STANDALONE = true'); process.exit(1); }
}
console.log(`built ${out} (build ${build}${test ? '-test' : ''})`);
